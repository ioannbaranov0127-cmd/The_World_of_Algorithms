def _quiz(task_id: int, text: str, correct_label: str, wrong_label: str) -> dict:
    return {
        'id': task_id,
        'kind': 'quiz',
        'category': 'theory',
        'type': 'quiz',
        'text': text,
        'hint': 'Выберите вариант, который соответствует теме.',
        'xp': 10,
        'options': [
            {'key': 'a', 'label': correct_label},
            {'key': 'b', 'label': wrong_label},
        ],
        'correct': 'a',
    }


